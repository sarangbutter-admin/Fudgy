#!/bin/bash
# Joins every database migration, oldest first, into supabase/setup-all.sql.
# Paste that one file into Supabase -> SQL Editor and press Run to set up a new project.
cd "$(dirname "$0")/.."
out=supabase/setup-all.sql
{ echo "-- Callebrownies: the whole database in one file (generated by tools/setup-sql.sh, do not edit)."
  echo "-- Paste into Supabase -> SQL Editor -> New query, then Run. Safe to run again."
  for m in supabase/migrations/*.sql; do printf '\n-- ===== %s =====\n' "$(basename "$m")"; cat "$m"; echo; done; } > "$out"
echo "$out"
